//! The Wasm specification defines small-step reduction rules for all instructions so that a list of
//! instructions can be reduced to some result value under some context C.
//!
//! An interpreter instead executes the instructions one by one with some interpreter state
//! [`State`](crate::execution::instructions::State). This iterative execution logic can be split
//! into two parts: (1) instruction handlers that correspond to small-step reductions and (2)
//! dispatching logic that decides when each instruction handler is called.
//!
//! This module deals with dispatching, i.e. deciding which instruction handler to execute and when.
//! Multiple dispatch mechanisms are available, each with their advantages and disadvantages. The
//! dispatch mechanism to use can be configured via [`Config::DISPATCH_MECHANISM`].

use crate::{
    execution::instructions::InterpreterLoopOutcome, Config, RuntimeError, Store, WasmResumable,
};

pub(crate) mod loop_call;
pub(crate) mod loop_match;
#[cfg(feature = "nightly")]
pub(crate) mod tail_calls;

/// The dispatch mechanism to use for interpreter execution.
///
/// The Wasm specification defines instructions as small-step reduction rules for which it is
/// straight-forward to define corresponding instruction handlers.
///
/// However, it does not define an algorithm for deciding which instruction handler to execute and
/// when. This work is done by a dispatch mechanism, of which there are three options (with one
/// requiring nightly).
///
/// This enum is marked as non-exhaustive due to the feature-dependent tail calls mechanism.
#[derive(Copy, Clone, Debug)]
#[non_exhaustive]
pub enum DispatchMechanism {
    /// Calls the instruction handler function for the next instruction in a loop.
    ///
    /// # Pros
    ///
    /// - **Good debugging experience**: The distinction between dispatching logic and instruction
    ///   handlers is very clear even at the machine code level. Every instruction handler has its own
    ///   function.
    ///
    /// # Cons
    ///
    /// - **(HYPOTHESIS) Slowest execution speed**: The compiler has less information available for optimization.
    LoopCall,
    /// Matches on the next instruction and executes its instruction handler in a loop.
    ///
    /// # Pros
    ///
    /// - **(HYPOTHESIS) Small binary size**: With all instruction handlers in one big match
    ///   statement, the compiler might be able to optimize better.
    ///
    /// # Cons
    ///
    /// - **Worse debugging experience**: As the compiler is free to optimize, the connection
    ///   between source and machine code might become unclear. This leads to a degradation of debug
    ///   info quality.
    LoopMatch,
    /// Instruction handler functions tail-call to the next instruction handler function.
    ///
    /// # Pros
    ///
    /// - **(HYPOTHESIS) The fastest mechanism**: Number of function calls is minimal with 1
    ///   function call per instruction. Branch prediction can optimize for commonly executed Wasm
    ///   instruction sequences.
    /// - **Good debugging experience**: Very similar to [`DispatchMechanism::LoopCall`], except
    ///   that the dispatch handler is at the end of every instruction handler function.
    ///
    /// # Cons
    ///
    /// - **(HYPOTHESIS) Larger binary sizes (lower binary sizes are WIP)**: The dispatch handler
    ///   inserted at the end of every instruction handler function be optimized with care.
    #[cfg(feature = "nightly")]
    TailCalls,
}

/// # Safety
///
/// The given resumable must be valid in the given [`Store`] and the store itself must be valid.
pub(crate) unsafe fn run<T: Config>(
    resumable: &mut WasmResumable,
    store: &mut Store<T>,
) -> Result<InterpreterLoopOutcome, RuntimeError> {
    match T::DISPATCH_MECHANISM {
        DispatchMechanism::LoopCall => {
            // SAFETY: The caller ensures that the resumable is valid in this store and that the
            // store is valid itself.
            unsafe { loop_call::run(resumable, store) }
        }
        DispatchMechanism::LoopMatch => {
            // SAFETY: The caller ensures that the resumable is valid in this store and that the
            // store is valid itself.
            unsafe { loop_match::run(resumable, store) }
        }
        #[cfg(feature = "nightly")]
        DispatchMechanism::TailCalls => {
            // SAFETY: The caller ensures that the resumable is valid in this store and that the
            // store is valid itself.
            unsafe { tail_calls::run(resumable, store) }
        }
    }
}

